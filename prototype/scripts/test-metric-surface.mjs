import assert from 'node:assert/strict';
import * as THREE from 'three';
import { solid } from '../src/art/ArtDetails.js';
import { GeometryFactory } from '../src/world/shared/GeometryFactory.js';
import { getMaterials, materialForSurface } from '../src/art/MaterialRegistry.js';
import { applyMetricSurfaceUVs } from '../src/art/MetricSurfaceUVs.js';
import { createStationContactShading } from '../src/art/StationContactShading.js';
const root=new THREE.Group(), m=getMaterials(), gf=new GeometryFactory();
const longZ=gf.buildWall(root,[],0,1.6,0,.22,3.2,9),longX=gf.buildWall(root,[],0,1.6,0,9,3.2,.22);
assert.equal(longZ.material,longX.material,'equal lengths must use equal physical repeat, independently of axis');
assert.equal(longZ.material.userData.repeatX,9);
const door=solid(root,m.doorWood,[0,1.175,0],[1.4,2.35,.08]);
const {position,normal,uv}=door.geometry.attributes;
const front=[];for(let i=0;i<normal.count;i++)if(normal.getZ(i)>.999)front.push(i);
const extent=(attribute,axis)=>Math.max(...front.map(i=>attribute[axis](i)))-Math.min(...front.map(i=>attribute[axis](i)));
assert(Math.abs(extent(uv,'getX')/extent(position,'getX')-1/.8)<1e-5,'wood grain texels follow metric width');
assert(Math.abs(extent(uv,'getY')/extent(position,'getY')-1/.8)<1e-5,'wood grain does not stretch to door height');
const plane=new THREE.PlaneGeometry(2,3),original=[...plane.attributes.uv.array];
applyMetricSurfaceUVs(plane,materialForSurface('wall',2,3));assert.deepEqual([...plane.attributes.uv.array],original,'cached repeat surfaces must not scale twice');
const desk=new THREE.Mesh(new THREE.BoxGeometry(1.4,.75,.72),new THREE.MeshStandardMaterial());desk.position.set(2,.375,-3);root.add(desk);
const contact=createStationContactShading({zoneGroup:root,workstations:[{desk}]});
assert.equal(contact.mesh.userData.footprints[0].x,2);assert.equal(contact.mesh.userData.footprints[0].z,-3);
assert.equal(contact.mesh.material.depthWrite,false);assert.equal(contact.mesh.castShadow,false);
let geometryReleased=0,textureReleased=0;contact.mesh.geometry.addEventListener('dispose',()=>geometryReleased++);contact.mesh.material.map.addEventListener('dispose',()=>textureReleased++);
contact.dispose();contact.dispose();assert.equal(geometryReleased,1);assert.equal(textureReleased,1);assert.equal(desk.parent,root);
console.log('PASS metric door grain, X/Z wall equality, no double repeat, stationary contact placement and idempotent ownership');
